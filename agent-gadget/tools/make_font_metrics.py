"""Write esp32_agent_gadget/font_metrics.h: pixel width of each ASCII character in the screen fonts 2 (s16) and 3 (s20).

The TJC fonts are anti-aliased Segoe UI rendered by the editor; their widths are not readable from the .zi files.
Calibration against a photo of the panel (2026-11-11): font 2 (Segoe UI Semibold, height 16) matches Segoe UI
Semibold at 13 px, font 3 (Semibold + bold, height 20) matches Segoe UI Bold at 15 px. Widths are rounded up, so
fitted text errs on the short side. Usage: python agent-gadget/tools/make_font_metrics.py
"""
import math
import os

from PIL import ImageFont

FONTS = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
TABLES = {"FONT_S16_W": ("seguisb.ttf", 13), "FONT_S20_W": ("segoeuib.ttf", 15)}


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "esp32_agent_gadget", "font_metrics.h")
    lines = ["// GENERATED by agent-gadget/tools/make_font_metrics.py - do not edit.",
             "// Pixel width of ASCII 32..126 in screen fonts 2 (s16) and 3 (s20); estimates rounded up.",
             "#pragma once", "#include <stdint.h>", ""]
    for name, (file, size) in TABLES.items():
        font = ImageFont.truetype(os.path.join(FONTS, file), size)
        widths = [math.ceil(font.getlength(chr(c))) for c in range(32, 127)]
        lines.append(f"static const uint8_t {name}[95] = {{")
        for i in range(0, 95, 19):
            lines.append("  " + ", ".join(str(w) for w in widths[i:i + 19]) + ",")
        lines.append("};")
        lines.append("")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(out)


if __name__ == "__main__":
    main()
